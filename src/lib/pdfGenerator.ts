import { jsPDF } from 'jspdf';

// ── HELPER GRAPHICS & COMPONENTS ──

function drawWatermark(doc: jsPDF, text: string) {
  doc.setTextColor(245, 247, 250);
  doc.setFontSize(70);
  doc.setFont('helvetica', 'bold');
  const w = doc.internal.pageSize.width;
  const h = doc.internal.pageSize.height;
  // @ts-ignore
  doc.text(text, w / 2, h / 2 + 20, { angle: 45, align: 'center' });
}

function drawHeader(doc: jsPDF, title: string, id: string) {
  const w = doc.internal.pageSize.width;
  
  // Top brand bar
  doc.setFillColor(15, 23, 42); // slate-900
  doc.rect(0, 0, w, 6, 'F');
  
  // Header background
  doc.setFillColor(255, 255, 255);
  doc.rect(0, 6, w, 34, 'F');
  
  // Logo
  doc.setTextColor(37, 99, 235); // blue-600
  doc.setFontSize(24);
  doc.setFont('helvetica', 'bold');
  doc.text('LoanIQ', 15, 25);
  doc.setFontSize(8);
  doc.setTextColor(100, 116, 139);
  doc.setFont('helvetica', 'normal');
  doc.text('INTELLIGENT LENDING SYSTEMS', 16, 32);

  // Title
  doc.setTextColor(15, 23, 42);
  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  doc.text(title.toUpperCase(), w - 15, 22, { align: 'right' });
  
  // Mock Barcode for Application ID
  doc.setFillColor(0, 0, 0);
  let barX = w - 65;
  const safeId = id || 'UNKNOWN';
  for (let i = 0; i < 20; i++) {
    const barW = (safeId.charCodeAt(i % safeId.length) % 3) + 0.5;
    doc.rect(barX, 26, barW, 8, 'F');
    barX += barW + 1;
  }
  doc.setFontSize(7);
  doc.setFont('helvetica', 'normal');
  doc.text(`REF: ${safeId}`, w - 15, 37, { align: 'right' });

  // Divider
  doc.setDrawColor(226, 232, 240);
  doc.setLineWidth(1);
  doc.line(15, 42, w - 15, 42);
}

function drawFooter(doc: jsPDF) {
  const h = doc.internal.pageSize.height;
  const w = doc.internal.pageSize.width;
  
  doc.setDrawColor(226, 232, 240);
  doc.setLineWidth(0.5);
  doc.line(15, h - 15, w - 15, h - 15);
  
  doc.setFontSize(7);
  doc.setTextColor(148, 163, 184);
  doc.text(`Generated by LoanIQ Secure Engine • ${new Date().toLocaleString()}`, 15, h - 10);
  doc.text('CONFIDENTIAL & PROPRIETARY', w - 15, h - 10, { align: 'right' });
}

function drawBox(doc: jsPDF, x: number, y: number, w: number, h: number, title: string) {
  // Shadow mock
  doc.setFillColor(241, 245, 249);
  doc.roundedRect(x + 1, y + 1, w, h, 2, 2, 'F');
  
  // Box
  doc.setFillColor(255, 255, 255);
  doc.setDrawColor(203, 213, 225);
  doc.setLineWidth(0.3);
  doc.roundedRect(x, y, w, h, 2, 2, 'FD');
  
  // Title ribbon
  doc.setFillColor(248, 250, 252);
  doc.roundedRect(x, y, w, 8, 2, 2, 'F');
  // straight line to cover bottom rounded corners of ribbon
  doc.rect(x, y + 6, w, 2, 'F');
  doc.line(x, y + 8, x + w, y + 8);
  
  doc.setFontSize(8);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(71, 85, 105);
  doc.text(title.toUpperCase(), x + 4, y + 5.5);
}

function drawDataRow(doc: jsPDF, startX: number, startY: number, items: {l: string, v: string, c?: [number,number,number]}[], colW: number) {
  items.forEach((item, i) => {
    const x = startX + (i * colW);
    doc.setFontSize(7);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(148, 163, 184);
    doc.text(item.l.toUpperCase(), x, startY);
    
    doc.setFontSize(9);
    doc.setFont('helvetica', 'bold');
    if (item.c) {
      doc.setTextColor(item.c[0], item.c[1], item.c[2]);
    } else {
      doc.setTextColor(15, 23, 42);
    }
    doc.text(String(item.v || 'N/A'), x, startY + 4);
  });
}

function drawGauge(doc: jsPDF, x: number, y: number, w: number, score: number) {
  const h = 4;
  const min = 300, max = 900;
  const val = Math.max(min, Math.min(max, score || 0));
  const p = (val - min) / (max - min);
  
  // Background tracks
  doc.setFillColor(239, 68, 68); // Red
  doc.rect(x, y, w * 0.35, h, 'F');
  doc.setFillColor(245, 158, 11); // Yellow
  doc.rect(x + w * 0.35, y, w * 0.35, h, 'F');
  doc.setFillColor(34, 197, 94); // Green
  doc.rect(x + w * 0.70, y, w * 0.30, h, 'F');
  
  // Marker
  const mx = x + (w * p);
  doc.setFillColor(15, 23, 42);
  doc.triangle(mx, y - 1, mx - 2, y - 4, mx + 2, y - 4, 'F');
  doc.setDrawColor(255, 255, 255);
  doc.setLineWidth(0.5);
  doc.line(mx, y, mx, y + h);
  
  doc.setFontSize(7);
  doc.setTextColor(148, 163, 184);
  doc.setFont('helvetica', 'normal');
  doc.text('300', x, y + h + 4);
  doc.text('900', x + w, y + h + 4, { align: 'right' });
  
  doc.setFontSize(12);
  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.text(val.toString(), mx, y - 5, { align: 'center' });
}

