export function generateApplicationReviewPDF(app: any) {
  const doc = new jsPDF();
  drawWatermark(doc, 'INTERNAL REVIEW');
  drawHeader(doc, 'Credit Application Review', app.id);
  
  const w = doc.internal.pageSize.width;
  let y = 50;
  
  // Status Ribbon
  doc.setFillColor(app.decision === 'APPROVED' ? 34 : (app.decision === 'REJECTED' ? 239 : 245), 
                   app.decision === 'APPROVED' ? 197 : (app.decision === 'REJECTED' ? 68 : 158), 
                   app.decision === 'APPROVED' ? 94 : (app.decision === 'REJECTED' ? 68 : 11));
  doc.rect(15, y, w - 30, 8, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(9);
  doc.setFont('helvetica', 'bold');
  doc.text(`CURRENT STATUS: ${app.decision || 'PENDING'}`, w / 2, y + 5.5, { align: 'center' });
  y += 15;
  
  // Applicant Box
  drawBox(doc, 15, y, w - 30, 25, '1. Applicant Profile');
  drawDataRow(doc, 20, y + 14, [
    { l: 'Full Legal Name', v: app.customerDetails?.name },
    { l: 'PAN ID', v: app.customerDetails?.panNumber },
    { l: 'Application Date', v: app.createdAt ? new Date(app.createdAt).toLocaleDateString() : 'N/A' }
  ], (w - 40) / 3);
  y += 30;
  
  // Financial Box
  drawBox(doc, 15, y, w - 30, 35, '2. Financial Snapshot');
  drawDataRow(doc, 20, y + 14, [
    { l: 'Requested Amount', v: `INR ${(app.financialDetails?.requestedAmount || 0).toLocaleString()}` },
    { l: 'Reported Income', v: `INR ${(app.financialDetails?.income || 0).toLocaleString()}` },
    { l: 'Employment Status', v: app.financialDetails?.jobType }
  ], (w - 40) / 3);
  drawDataRow(doc, 20, y + 26, [
    { l: 'Loan Purpose', v: app.financialDetails?.loanPurpose },
    { l: 'Calculated Risk Tier', v: app.riskLevel, c: app.riskLevel === 'LOW' ? [34,197,94] : [239,68,68] }
  ], (w - 40) / 3);
  y += 40;
  
  // Credit Gauge & AI Box
  drawBox(doc, 15, y, w - 30, 50, '3. AI Underwriting & Credit Risk');
  
  doc.setFontSize(7);
  doc.setTextColor(148, 163, 184);
  doc.setFont('helvetica', 'normal');
  doc.text('CREDIT SCORE METER', 20, y + 15);
  drawGauge(doc, 20, y + 25, 80, app.creditScore || 0);
  
  doc.setDrawColor(226, 232, 240);
  doc.line(110, y + 12, 110, y + 45); // vertical divider
  
  doc.text('AI UNDERWRITING SUMMARY', 115, y + 15);
  doc.setFontSize(8);
  doc.setTextColor(15, 23, 42);
  if (app.explanation) {
    const splitText = doc.splitTextToSize(app.explanation, w - 135);
    doc.text(splitText, 115, y + 21);
  } else {
    doc.text('No AI explanation provided.', 115, y + 21);
  }

  drawFooter(doc);
  doc.save(`LoanIQ_Credit_Review_${app.id?.substring(0, 8).toUpperCase() || 'Report'}.pdf`);
}

export function generateKYCVerificationPDF(app: any) {
  const doc = new jsPDF();
  drawWatermark(doc, 'KYC AUDIT');
  drawHeader(doc, 'KYC Compliance Report', app.id);
  
  const w = doc.internal.pageSize.width;
  let y = 50;
  
  // Subject Box
  drawBox(doc, 15, y, w - 30, 25, 'Subject Identity Information');
  drawDataRow(doc, 20, y + 14, [
    { l: 'Subject Name', v: app.customerDetails?.name },
    { l: 'Tax ID (PAN)', v: app.customerDetails?.panNumber },
    { l: 'Audit Date', v: new Date().toLocaleDateString() }
  ], (w - 40) / 3);
  y += 30;
  
  // Checks Box
  drawBox(doc, 15, y, w - 30, 45, 'Automated Verification Matrix');
  
  const isLivenessPass = !!app.verification?.liveness;
  const isPanVerified = !!app.verification?.panVerified;
  
  drawDataRow(doc, 20, y + 14, [
    { l: 'Liveness Confidence Check', v: isLivenessPass ? 'VERIFIED' : 'FAILED', c: isLivenessPass ? [34,197,94] : [239,68,68] },
    { l: 'PAN Authority Match', v: isPanVerified ? 'VERIFIED' : 'FAILED', c: isPanVerified ? [34,197,94] : [239,68,68] }
  ], (w - 40) / 2);
  
  // Bar visualization for Face Match
  doc.setFontSize(7);
  doc.setTextColor(148, 163, 184);
  doc.setFont('helvetica', 'normal');
  doc.text('BIOMETRIC FACE MATCH CONFIDENCE', 20, y + 28);
  
  const matchScore = app.verification?.faceMatchScore || 0;
  doc.setFillColor(241, 245, 249);
  doc.rect(20, y + 32, (w - 40), 6, 'F');
  
  doc.setFillColor(matchScore >= 80 ? 34 : (matchScore >= 50 ? 245 : 239), 
                   matchScore >= 80 ? 197 : (matchScore >= 50 ? 158 : 68), 
                   matchScore >= 80 ? 94 : (matchScore >= 50 ? 11 : 68));
  doc.rect(20, y + 32, ((w - 40) * (matchScore / 100)), 6, 'F');
  
  doc.setFontSize(8);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(255, 255, 255);
  if (matchScore > 10) {
    doc.text(`${matchScore}% MATCH`, 22, y + 36.5);
  }
  
  y += 50;
  
  // Conclusion Box
  const isFullyVerified = isLivenessPass && isPanVerified;
  doc.setFillColor(isFullyVerified ? 240 : 254, isFullyVerified ? 253 : 242, isFullyVerified ? 244 : 242);
  doc.setDrawColor(isFullyVerified ? 187 : 252, isFullyVerified ? 247 : 165, isFullyVerified ? 208 : 165);
  doc.setLineWidth(0.5);
  doc.roundedRect(15, y, w - 30, 20, 2, 2, 'FD');
  
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(isFullyVerified ? 21 : 153, isFullyVerified ? 128 : 27, isFullyVerified ? 61 : 27);
  doc.text(isFullyVerified ? 'COMPLIANCE AUDIT PASSED' : 'COMPLIANCE AUDIT FAILED', w / 2, y + 8, { align: 'center' });
  
  doc.setFontSize(8);
  doc.setFont('helvetica', 'normal');
  doc.text(isFullyVerified 
    ? 'All automated regulatory and identity checks have cleared successfully.' 
    : 'Identity checks failed. Manual intervention and physical verification required.', 
    w / 2, y + 14, { align: 'center' });

  drawFooter(doc);
  doc.save(`LoanIQ_KYC_Audit_${app.id?.substring(0, 8).toUpperCase() || 'Report'}.pdf`);
}

